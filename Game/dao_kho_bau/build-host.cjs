'use strict';
// Builds a local, reviewable Apps Script include. Does not deploy or upload assets.
const fs=require('node:fs'),path=require('node:path');
const root=__dirname;
const args=process.argv.slice(2),at=args.indexOf('--asset-base'),production=args.includes('--production');
let assetBase=args[at+1];
if(production){
  const hosting=JSON.parse(fs.readFileSync(path.join(root,'assets/hosting.json'),'utf8'));
  if(!/^https:\/\/raw\.githubusercontent\.com\/bungbutq\/zeva-education-app\/[a-f0-9]{40}\/Game\/dao_kho_bau\/$/.test(hosting.baseURL))throw Error('Unexpected immutable artwork host');
  const expected=[...JSON.parse(fs.readFileSync(path.join(root,'assets/manifest.json'),'utf8')).map(x=>x.file),'Nunito.ttf','OFL.txt'];
  if(expected.length!==hosting.files.length||expected.some(name=>!hosting.files.some(entry=>entry.path===name)))throw Error('Incomplete published asset manifest');
  const crypto=require('node:crypto');
  for(const entry of hosting.files){const raw=fs.readFileSync(path.join(root,'assets',entry.path));if(raw.length!==entry.bytes||crypto.createHash('sha256').update(raw).digest('hex')!==entry.sha256)throw Error('Publish changed asset first: '+entry.path);}
  assetBase=hosting.baseURL;
}else if(at<0||!assetBase)throw Error('Usage: node game/dao-kho-bau/build-host.cjs --production OR --asset-base https://your-static-host/game/dao-kho-bau/');
const base=new URL(assetBase);
if(!['https:','http:'].includes(base.protocol))throw Error('Asset base must be HTTP(S).');
if(base.protocol==='http:'&&!['127.0.0.1','localhost','[::1]'].includes(base.hostname))throw Error('Production assets must use HTTPS.');
if(!base.pathname.endsWith('/'))base.pathname+='/';
const escape=v=>String(v).replace(/&/g,'&amp;').replace(/"/g,'&quot;').replace(/</g,'&lt;');
let doc=fs.readFileSync(path.join(root,'index.html'),'utf8');
doc=doc.replace('<head>','<head><base href="'+escape(base.href)+'">');
doc=doc.replace('<link rel="stylesheet" href="styles.css">',()=>'<style>'+fs.readFileSync(path.join(root,'styles.css'),'utf8')+'</style>');
doc=doc.replace('<link rel="stylesheet" href="art-ui.css">',()=>'<style>'+fs.readFileSync(path.join(root,'art-ui.css'),'utf8')+'</style>');
doc=doc.replace('<link rel="stylesheet" href="island-art.css">',()=>'<style>'+fs.readFileSync(path.join(root,'island-art.css'),'utf8')+'</style>');
doc=doc.replace('<link rel="stylesheet" href="shipyard.css">',()=>'<style>'+fs.readFileSync(path.join(root,'shipyard.css'),'utf8')+'</style>');
for(const name of ['map-routes.js','map-layout.js','map-camera.js','shipyard.js','island-rules.js','trade.js','engine.js','questions.js','data-source.js','artwork.js','atmosphere-effects.js','life-effects.js','artwork-renderer.js','effects.js','port-water.js','trade-ui.js','shipyard-ui.js','audio.js','game.js']){
  let source=fs.readFileSync(path.join(root,name),'utf8');
  if(production&&name==='audio.js'){
    const hosting=JSON.parse(fs.readFileSync(path.join(root,'audio/hosting.json'),'utf8'));
    if(!/^https:\/\/raw\.githubusercontent\.com\/bungbutq\/zeva-education-app\/[a-f0-9]{40}\/Game\/dao_kho_bau\/audio\/$/.test(hosting.baseURL))throw Error('Unexpected immutable audio host');
    const crypto=require('node:crypto'),expected=JSON.parse(fs.readFileSync(path.join(root,'audio/manifest.json'),'utf8')).files;
    if(JSON.stringify(expected)!==JSON.stringify(hosting.files))throw Error('Publish changed audio manifest first');
    for(const entry of expected){
      if(path.basename(entry.path)!==entry.path)throw Error('Invalid audio path');
      const raw=fs.readFileSync(path.join(root,'audio',entry.path));
      if(raw.length!==entry.bytes||crypto.createHash('sha256').update(raw).digest('hex')!==entry.sha256)throw Error('Publish changed audio first: '+entry.path);
    }
    source=source.replace("const BASE = 'audio/';",'const BASE = '+JSON.stringify(hosting.baseURL)+';');
  }
  doc=doc.replace('<script src="'+name+'"></script>',()=>'<script>'+source.replace(/<\/script/gi,'<\\/script')+'</script>');
}
let host=fs.readFileSync(path.join(root,'zeva-host.html'),'utf8');
host=host.replace("url('assets/map-board-clean.png')","url('"+new URL('assets/map-board-clean.png',base).href+"')");
host=host.replace('<!-- TREASURE_DOCUMENT -->',()=>'<script type="application/json" id="ztbTemplate">'+JSON.stringify(doc).replace(/</g,'\\u003c').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029')+'</script>');
const out=path.join(root,'dist');fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(path.join(out,'client_treasure_game.html'),host);
if(production)fs.writeFileSync(path.resolve(root,'../../client_106_treasure_game.html'),'<!-- GENERATED by game/dao-kho-bau/build-host.cjs --production; edit the game source. -->\n'+host);
console.log('Built '+path.join(out,'client_treasure_game.html')+'; assets: '+base.href);
